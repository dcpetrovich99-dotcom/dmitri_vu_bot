def quiz_result(score: int) -> str:
    total = len(QUIZ)
    if score == total:
        verdict = "Отличный результат — знание правил на высоком уровне."
    elif score >= total - 1:
        verdict = "Хороший результат, основные правила усвоены."
    elif score >= total // 2:
        verdict = "Неплохо, но некоторые темы стоит повторить."
    else:
        verdict = "Правила пока даются непросто — обучение с инструктором поможет."
    return (
        f"Тест завершён. Правильных ответов: {score} из {total}.\n"
        f"{verdict}\n\n"
        "Записаться на обучение или задать вопрос можно через заявку."
    )
